#!/usr/bin/env node
/**
 * scripts/patch-standalone.js
 *
 * Runs automatically after `next build` (via postbuild in package.json).
 * Patches .next/standalone/server.js to serve /_next/static/ and public/
 * assets directly via Node.js fs streams — before Next.js request handler.
 *
 * WHY: cPanel Phusion Passenger routes ALL requests through Node.js.
 * There is no Nginx/Apache layer to serve static files separately.
 * The generated standalone/server.js uses startServer() which cannot be
 * intercepted — so we replace it with http.createServer() + getRequestHandler().
 *
 * The nextConfig JSON block is extracted dynamically from the build output
 * so all Midtrans, Prisma, serverActions, and other configs remain intact.
 */

"use strict";

const fs   = require("fs");
const path = require("path");

const ROOT          = path.join(__dirname, "..");
const STANDALONE    = path.join(ROOT, ".next", "standalone");
const SERVER_JS     = path.join(STANDALONE, "server.js");

// ── Validate ─────────────────────────────────────────────────────────────────
if (!fs.existsSync(SERVER_JS)) {
  console.error("❌  patch-standalone: .next/standalone/server.js not found.");
  console.error("    Run `npm run build` first.");
  process.exit(1);
}

// ── Always read from the original unpatched file if available ────────────────
// This makes the script idempotent: re-running it on an already-patched file
// still produces a correct result (not a double-patched broken one).
const backupPath = SERVER_JS + ".orig";
const sourcePath = fs.existsSync(backupPath) ? backupPath : SERVER_JS;
const original   = fs.readFileSync(sourcePath, "utf-8");

// ── Extract nextConfig JSON block ────────────────────────────────────────────
// Next.js embeds the full config as a single-line JSON object.
// We locate it by its known surrounding tokens to survive any future
// reordering of the generated file.
const START_MARKER = "const nextConfig = ";
const END_MARKER   = "\n\nprocess.env.__NEXT_PRIVATE_STANDALONE_CONFIG";

const startIdx = original.indexOf(START_MARKER);
const endIdx   = original.indexOf(END_MARKER, startIdx);

if (startIdx === -1 || endIdx === -1) {
  console.error("❌  patch-standalone: Could not locate nextConfig in server.js.");
  console.error("    The Next.js version may have changed its output format.");
  process.exit(1);
}

// Strip any trailing semicolon (present when patching an already-patched file)
let nextConfigStr = original.slice(startIdx + START_MARKER.length, endIdx).trimEnd();
if (nextConfigStr.endsWith(";")) nextConfigStr = nextConfigStr.slice(0, -1);

// Validate that it is parseable JSON before writing anything
try {
  JSON.parse(nextConfigStr);
} catch (e) {
  console.error("❌  patch-standalone: Extracted nextConfig is not valid JSON:", e.message);
  process.exit(1);
}

// ── Build patched server ──────────────────────────────────────────────────────
const patched = `'use strict';
// ─── PATCHED BY scripts/patch-standalone.js ────────────────────────────────
// DO NOT EDIT MANUALLY — regenerated by \`npm run build\`.
//
// Replaces the default startServer() with an http.createServer() wrapper that
// serves /_next/static/ and public/ files directly via fs streams (with correct
// MIME types and caching headers), then falls through to Next.js for everything
// else. Required for cPanel/Phusion Passenger where there is no Nginx/Apache
// static-file layer in front of Node.js.
// ─────────────────────────────────────────────────────────────────────────────

const path = require('path');
const http = require('http');
const fs   = require('fs');
const url  = require('url');

// ── Directory context ─────────────────────────────────────────────────────────
const dir = path.join(__dirname);

process.env.NODE_ENV = 'production';
process.chdir(__dirname);

// ── Server config ──────────────────────────────────────────────────────────────
const currentPort      = parseInt(process.env.PORT, 10) || 3000;
const hostname         = process.env.HOSTNAME || '0.0.0.0';
const keepAliveEnv     = parseInt(process.env.KEEP_ALIVE_TIMEOUT, 10);
const keepAliveTimeout = (!Number.isNaN(keepAliveEnv) && Number.isFinite(keepAliveEnv) && keepAliveEnv >= 0)
  ? keepAliveEnv
  : undefined;

// ── Preserve original nextConfig (auto-extracted from build output) ───────────
// This block is the source of truth — do not modify manually.
const nextConfig = ${nextConfigStr};

process.env.__NEXT_PRIVATE_STANDALONE_CONFIG = JSON.stringify(nextConfig);

// ── Inline MIME map (no extra dependency) ─────────────────────────────────────
const MIME_TYPES = {
  '.js':          'application/javascript; charset=utf-8',
  '.mjs':         'application/javascript; charset=utf-8',
  '.css':         'text/css; charset=utf-8',
  '.html':        'text/html; charset=utf-8',
  '.json':        'application/json; charset=utf-8',
  '.png':         'image/png',
  '.jpg':         'image/jpeg',
  '.jpeg':        'image/jpeg',
  '.webp':        'image/webp',
  '.gif':         'image/gif',
  '.svg':         'image/svg+xml; charset=utf-8',
  '.ico':         'image/x-icon',
  '.woff':        'font/woff',
  '.woff2':       'font/woff2',
  '.ttf':         'font/ttf',
  '.otf':         'font/otf',
  '.eot':         'application/vnd.ms-fontobject',
  '.txt':         'text/plain; charset=utf-8',
  '.xml':         'application/xml; charset=utf-8',
  '.webmanifest': 'application/manifest+json; charset=utf-8',
  '.map':         'application/json',
  '.mp4':         'video/mp4',
  '.webm':        'video/webm',
  '.mp3':         'audio/mpeg',
  '.pdf':         'application/pdf',
};

function getMime(filePath) {
  const ext = path.extname(filePath).toLowerCase();
  return MIME_TYPES[ext] || 'application/octet-stream';
}

// ── Static file streamer ──────────────────────────────────────────────────────
// Returns true if file was found and streamed; false to fall through to Next.js.
function tryServeFile(filePath, cacheControl, req, res) {
  return new Promise((resolve) => {
    fs.stat(filePath, (statErr, stat) => {
      if (statErr || !stat.isFile()) { resolve(false); return; }

      // Handle conditional GET (ETag / If-None-Match)
      const etag = '"' + stat.mtime.getTime().toString(16) + '-' + stat.size.toString(16) + '"';
      if (req.headers['if-none-match'] === etag) {
        res.writeHead(304, { 'ETag': etag, 'Cache-Control': cacheControl });
        res.end();
        resolve(true);
        return;
      }

      res.writeHead(200, {
        'Content-Type':   getMime(filePath),
        'Content-Length': stat.size,
        'Cache-Control':  cacheControl,
        'ETag':           etag,
      });
      const stream = fs.createReadStream(filePath);
      stream.on('error', () => { res.end(); });
      stream.pipe(res);
      resolve(true);
    });
  });
}

// ── Boot Next.js ──────────────────────────────────────────────────────────────
// require('next') in CJS returns the factory function directly (no .default).
const next = require('next');

const app = next({ dir, dev: false, conf: nextConfig });

app.prepare().then(() => {
  const nextHandler = app.getRequestHandler();

  const server = http.createServer(async (req, res) => {
    const parsedUrl = url.parse(req.url || '/', true);
    const pathname  = parsedUrl.pathname || '/';

    try {
      // ── 1. /_next/static/* ─ immutable, 1-year cache ───────────────────────
      if (pathname.startsWith('/_next/static/')) {
        const rel      = pathname.slice('/_next/static/'.length);
        const filePath = path.join(__dirname, '.next', 'static', decodeURIComponent(rel));
        const served   = await tryServeFile(filePath, 'public, max-age=31536000, immutable', req, res);
        if (served) return;
        // Not found — let Next.js return its own 404
        nextHandler(req, res, parsedUrl);
        return;
      }

      // ── 2. public/* ─ 1-hour cache, existence-checked ─────────────────────
      if (pathname !== '/') {
        const filePath = path.join(__dirname, 'public', decodeURIComponent(pathname));
        const served   = await tryServeFile(filePath, 'public, max-age=3600', req, res);
        if (served) return;
      }

      // ── 3. Everything else → Next.js ───────────────────────────────────────
      nextHandler(req, res, parsedUrl);

    } catch (err) {
      console.error('[server] Unhandled error for', req.url, err);
      if (!res.headersSent) {
        res.writeHead(500);
        res.end('Internal Server Error');
      }
    }
  });

  if (keepAliveTimeout !== undefined) {
    server.keepAliveTimeout = keepAliveTimeout;
  }

  server.listen(currentPort, hostname, () => {
    console.log('> Ready on http://' + hostname + ':' + currentPort);
  });

  server.on('error', (err) => {
    console.error('[server] Fatal:', err);
    process.exit(1);
  });

}).catch((err) => {
  console.error('[next] prepare() failed:', err);
  process.exit(1);
});
`;

// ── Write patched file ────────────────────────────────────────────────────────
// backupPath already declared above — keep original unpatched file for next run
if (!fs.existsSync(backupPath)) {
  fs.copyFileSync(SERVER_JS, backupPath);
}
fs.writeFileSync(SERVER_JS, patched, "utf-8");

console.log("✅  patch-standalone: .next/standalone/server.js patched successfully.");
console.log("    Static interceptor active for /_next/static/ and public/.");
